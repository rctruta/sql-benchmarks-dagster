"""Client for benchmarking Malloy Publisher (the semantic layer over DuckDB).

The Publisher serves *packages* (directories of .malloy models + data files)
over REST. This client manages a local bench package: bulk_load writes the
partition's parquet plus a generated model file into the package directory,
and run_query POSTs Malloy query text to the Publisher's query endpoint.

Cold discipline: the Publisher has no cache-clear endpoint, so engine-level
cold start = docker restart of the Publisher container before each query,
mirroring the per-query server restart in QuackClient.

REST contract (verified against ms2data/malloy-publisher:latest, 2026-07-14):
  POST /api/v0/environments/{env}/packages/{pkg}/models/{model}/query
  body: {"query": "<malloy query text>"}
"""
import json
import os
import re
import subprocess
import time
import urllib.request

import logging

from ..utils.system import thrash_os_cache
from .storage import DataStore

logger = logging.getLogger("dagster")

_SAFE_IDENT = re.compile(r"^\w+$")

MODEL_HEADER = "// Generated by sqlbenchdag malloy engine — do not edit.\n"
MODEL_TEMPLATE = "source: {table} is duckdb.table('{parquet}')\n"


class MalloyClient:
    def __init__(self, store: DataStore, port: int, environment: str,
                 package: str, container: str, ready_timeout_s: float = 60.0):
        # All package writes go through the store — the store owns WHERE the
        # data lives and (for MountedVolumeStore) verifies the container can
        # actually see it. The client never joins its own data paths.
        self.store = store
        self.port = port
        self.environment = environment
        self.package = package
        self.container = container
        self.ready_timeout_s = ready_timeout_s
        self._ensure_manifests()

    def _ensure_manifests(self) -> None:
        """A Publisher package requires publisher.json; malloy-config.json
        declares the duckdb connection (shape copied from the faa sample)."""
        if not os.path.exists(os.path.join(self.store.root, "publisher.json")):
            self.store.put_text(
                json.dumps({"name": self.package, "version": "1.0.0",
                            "description": "sqlbenchdag bench package "
                                           "(generated; do not edit)"}, indent=2),
                "publisher.json")
        if not os.path.exists(os.path.join(self.store.root, "malloy-config.json")):
            self.store.put_text(
                json.dumps({"connections": {"duckdb": {
                    "is": "duckdb", "workingDirectory": self.package,
                    "securityPolicy": "none"}}}, indent=2),
                "malloy-config.json")

    # --- data loading -----------------------------------------------------

    def _model_name(self, partition_key: str) -> str:
        # One model per partition, holding one source per loaded table.
        return f"bench_{partition_key}.malloy"

    def bulk_load(self, filepath: str, target_table_name: str,
                  partition_key: str, table_def: dict = None) -> None:
        if not _SAFE_IDENT.match(target_table_name):
            raise ValueError(f"unsafe table name: {target_table_name!r}")
        if not _SAFE_IDENT.match(partition_key):
            raise ValueError(f"unsafe partition key: {partition_key!r}")
        filepath = os.path.realpath(filepath)
        parquet_name = f"{target_table_name}_{partition_key}.parquet"
        dest = self.store.put_file(filepath, parquet_name)
        model_name = self._model_name(partition_key)
        line = MODEL_TEMPLATE.format(table=target_table_name,
                                     parquet=parquet_name)
        model_path = os.path.join(self.store.root, model_name)
        existing = open(model_path).read() if os.path.exists(model_path) else ""
        if line not in existing:
            content = (existing or MODEL_HEADER) + line
            self.store.put_text(content, model_name)
        logger.info("malloy bulk_load via %s: %s -> %s (+%s)",
                    self.store.describe(), filepath, dest, model_name)

    # --- cold start -------------------------------------------------------

    def restart_server(self) -> None:
        subprocess.run(["docker", "restart", self.container],
                       check=True, capture_output=True)
        self._wait_ready()

    def _wait_ready(self) -> None:
        url = f"http://localhost:{self.port}/api/v0/environments"
        deadline = time.monotonic() + self.ready_timeout_s
        while time.monotonic() < deadline:
            try:
                with urllib.request.urlopen(url, timeout=2) as r:
                    if r.status == 200:
                        return
            except Exception:
                time.sleep(0.5)
        raise RuntimeError(
            f"malloy publisher on :{self.port} not ready within "
            f"{self.ready_timeout_s}s after restart")

    # --- query ------------------------------------------------------------

    def run_query(self, malloy_query: str, partition_key: str):
        """Cold-start the server, POST the Malloy query, return wall seconds.

        The measured duration deliberately includes Malloy compilation and the
        HTTP round trip: that IS the semantic-layer cost under test. Compare
        against the duckdb engine's in-process wall time on identical data.
        """
        thrash_os_cache()
        self.restart_server()

        model = self._model_name(partition_key)
        url = (f"http://localhost:{self.port}/api/v0/environments/"
               f"{self.environment}/packages/{self.package}/models/{model}/query")
        payload = json.dumps({"query": malloy_query}).encode()
        req = urllib.request.Request(
            url, data=payload, headers={"Content-Type": "application/json"},
            method="POST")

        start = time.perf_counter()
        with urllib.request.urlopen(req, timeout=600) as r:
            body = r.read()
            status = r.status
        duration = time.perf_counter() - start

        if status != 200:
            raise RuntimeError(f"malloy query failed HTTP {status}: {body[:300]!r}")
        parsed = json.loads(body)
        if "result" not in parsed:
            raise RuntimeError(f"malloy query returned no result: {body[:300]!r}")
        logger.info("malloy query ok partition=%s duration=%.4fs",
                    partition_key, duration)
        return duration

    def fetch_rows(self, malloy_query: str, partition_key: str) -> list:
        """Execute and return result rows (for the equivalence gate, not timing)."""
        self._wait_ready()
        model = self._model_name(partition_key)
        url = (f"http://localhost:{self.port}/api/v0/environments/"
               f"{self.environment}/packages/{self.package}/models/{model}/query")
        payload = json.dumps({"query": malloy_query}).encode()
        req = urllib.request.Request(
            url, data=payload, headers={"Content-Type": "application/json"},
            method="POST")
        with urllib.request.urlopen(req, timeout=600) as r:
            parsed = json.loads(r.read())
        result = json.loads(parsed["result"])
        rows = []
        for rec in result["data"]["array_value"]:
            row = {}
            for f, cell in zip(result["schema"]["fields"], rec["record_value"]):
                row[f["name"]] = cell.get("number_value", cell.get("string_value"))
            rows.append(row)
        return rows
